#!/usr/bin/env node
/**
 * Генерирует config/config.php из GitHub Secrets / env перед FTP-деплоем.
 *
 * Secrets:
 *   WWM_APP_SECRET              (обязательно)
 *   WWM_BASE_URL                (default: https://my.worldwatercolormasters.art)
 *   WWM_SMTP_USER, WWM_SMTP_PASS, WWM_SMTP_HOST
 *   WWM_WEBHOOK_PAYMENT_TOKEN, WWM_WEBHOOK_DEMO_TOKEN
 *   WWM_MAIL_ENABLED            (true/false)
 *   WWM_WEBHOOKS_ENABLED        (true/false)
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const outFile = join(root, 'config', 'config.php');

function phpString(value) {
  return `'${String(value).replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
}

function env(name, fallback = '') {
  return process.env[name] ?? fallback;
}

function envBool(name, fallback = false) {
  const v = process.env[name];
  if (v === undefined || v === '') return fallback;
  return /^(1|true|yes|on)$/i.test(v);
}

const appSecret = env('WWM_APP_SECRET');
if (!appSecret || appSecret.length < 32) {
  console.error('WWM_APP_SECRET must be at least 32 characters');
  process.exit(1);
}

const smtpUser = env('WWM_SMTP_USER');
const smtpPass = env('WWM_SMTP_PASS');
const mailEnabled = envBool('WWM_MAIL_ENABLED', Boolean(smtpUser && smtpPass));
const webhooksEnabled = envBool('WWM_WEBHOOKS_ENABLED', false);

const config = `<?php
/**
 * Auto-generated by scripts/write-deploy-config.mjs — do not edit on server.
 * Change values via GitHub Secrets and redeploy.
 */
return [
    'app_name' => 'World Watercolor Masters',
    'base_url' => ${phpString(env('WWM_BASE_URL', 'https://my.worldwatercolormasters.art'))},
    'timezone' => 'UTC',

    'db_path' => dirname(__DIR__) . '/data/wwm.sqlite',

    'app_secret' => ${phpString(appSecret)},

    'webhooks' => [
        'payment_token' => ${phpString(env('WWM_WEBHOOK_PAYMENT_TOKEN'))},
        'demo_token' => ${phpString(env('WWM_WEBHOOK_DEMO_TOKEN'))},
        'enabled' => ${webhooksEnabled ? 'true' : 'false'},
    ],

    'mail' => [
        'enabled' => ${mailEnabled ? 'true' : 'false'},
        'from_email' => ${phpString(env('WWM_SMTP_FROM', 'courses@bl-school.com'))},
        'from_name' => ${phpString(env('WWM_SMTP_FROM_NAME', 'World Watercolor Masters'))},
        'smtp_host' => ${phpString(env('WWM_SMTP_HOST'))},
        'smtp_port' => ${Number(env('WWM_SMTP_PORT', '587')) || 587},
        'smtp_user' => ${phpString(smtpUser)},
        'smtp_pass' => ${phpString(smtpPass)},
    ],

    'demo_hours' => ${Number(env('WWM_DEMO_HOURS', '48')) || 48},

    'log_enabled' => true,
    'log_file' => dirname(__DIR__) . '/data/cabinet.log',
];
`;

mkdirSync(dirname(outFile), { recursive: true });
writeFileSync(outFile, config, 'utf8');
console.log('Wrote', outFile);
