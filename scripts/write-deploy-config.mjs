#!/usr/bin/env node
/**
 * Генерирует config/config.php из GitHub Secrets / env перед FTP-деплоем.
 *
 * Secrets:
 *   WWM_APP_SECRET              (обязательно)
 *   WWM_BASE_URL                (default: https://my.worldwatercolormasters.art)
 *   WWM_SMTP_USER, WWM_SMTP_PASS, WWM_SMTP_HOST
 *   WWM_WEBHOOK_PAYMENT_TOKEN, WWM_WEBHOOK_DEMO_TOKEN
 *   WWM_MAIL_ENABLED            (true/false)
 *   WWM_WEBHOOKS_ENABLED        (true/false)
 *   WWM_AVO_ENABLED, WWM_AVO_SHOP_ID, WWM_AVO_API_KEY_GET, WWM_AVO_API_KEY_SET
 *   WWM_AVO_TAG_LOGGED_IN, WWM_AVO_TAG_DEMO_OPENED
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const outFile = join(root, 'config', 'config.php');

function phpString(value) {
  return `'${String(value).replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
}

function env(name, fallback = '') {
  const v = process.env[name];
  return v === undefined || v === '' ? fallback : v;
}

function envBool(name, fallback = false) {
  const v = process.env[name];
  if (v === undefined || v === '') return fallback;
  return /^(1|true|yes|on)$/i.test(v);
}

function phpAdminEmails(value) {
  const emails = String(value || '')
    .split(/[,;]+/)
    .map((email) => email.trim())
    .filter(Boolean);
  if (emails.length === 0) {
    return '[]';
  }
  return `[${emails.map(phpString).join(', ')}]`;
}

const appSecret = env('WWM_APP_SECRET');
if (!appSecret || appSecret.length < 32) {
  console.error('WWM_APP_SECRET must be at least 32 characters');
  process.exit(1);
}

const smtpUser = env('WWM_SMTP_USER');
const smtpPass = env('WWM_SMTP_PASS');
const mailEnabled = envBool('WWM_MAIL_ENABLED', Boolean(smtpUser && smtpPass));
const webhooksEnabled = envBool('WWM_WEBHOOKS_ENABLED', false);
const avoEnabled = envBool('WWM_AVO_ENABLED', false);
const avoTagLoggedIn = Number(env('WWM_AVO_TAG_LOGGED_IN', '0')) || 0;
const avoTagDemoOpened = Number(env('WWM_AVO_TAG_DEMO_OPENED', '0')) || 0;

const config = `<?php
/**
 * Auto-generated by scripts/write-deploy-config.mjs — do not edit on server.
 * Change values via GitHub Secrets and redeploy.
 */
return [
    'app_name' => 'World Watercolor Masters',
    'base_url' => ${phpString(env('WWM_BASE_URL', 'https://my.worldwatercolormasters.art'))},
    'timezone' => 'UTC',

    'db_path' => dirname(__DIR__) . '/data/wwm.sqlite',

    'app_secret' => ${phpString(appSecret)},

    'webhooks' => [
        'payment_token' => ${phpString(env('WWM_WEBHOOK_PAYMENT_TOKEN'))},
        'demo_token' => ${phpString(env('WWM_WEBHOOK_DEMO_TOKEN'))},
        'enabled' => ${webhooksEnabled ? 'true' : 'false'},
    ],

    'mail' => [
        'enabled' => ${mailEnabled ? 'true' : 'false'},
        'from_email' => ${phpString(env('WWM_SMTP_FROM', 'robot@worldwatercolormasters.art'))},
        'from_name' => ${phpString(env('WWM_SMTP_FROM_NAME', 'World Watercolor Masters'))},
        'smtp_host' => ${phpString(env('WWM_SMTP_HOST', 'smtp.spaceweb.ru'))},
        'smtp_port' => ${Number(env('WWM_SMTP_PORT', '465')) || 465},
        'smtp_encryption' => ${phpString(env('WWM_SMTP_ENCRYPTION', 'ssl'))},
        'smtp_verify_ssl' => ${envBool('WWM_SMTP_VERIFY_SSL', false) ? 'true' : 'false'},
        'smtp_user' => ${phpString(smtpUser)},
        'smtp_pass' => ${phpString(smtpPass)},
    ],

    'demo_hours' => ${Number(env('WWM_DEMO_HOURS', '48')) || 48},
    'magic_link_hours' => ${Number(env('WWM_MAGIC_LINK_HOURS', '72')) || 72},

    'asset_version' => ${phpString(env('WWM_ASSET_VERSION', '2'))},

    'demo_default_password' => ${phpString(env('WWM_DEMO_DEFAULT_PASSWORD', 'Gh45tyhf'))},

    'magic_link_login' => ${envBool('WWM_MAGIC_LINK_LOGIN', false) ? 'true' : 'false'},

    'avo_goods_to_course' => [
        188 => 'elke-en',
        191 => 'elke-de',
        193 => 'alvaro',
    ],

    'avo' => [
        'enabled' => ${avoEnabled ? 'true' : 'false'},
        'shop_id' => ${phpString(env('WWM_AVO_SHOP_ID', 'bl-school'))},
        'api_key_get' => ${phpString(env('WWM_AVO_API_KEY_GET'))},
        'api_key_set' => ${phpString(env('WWM_AVO_API_KEY_SET'))},
        'tags' => [
            'logged_in' => ${avoTagLoggedIn},
            'demo_opened' => ${avoTagDemoOpened},
        ],
    ],

    'admin_emails' => ${phpAdminEmails(env('WWM_ADMIN_EMAILS', 'eaalferov@yandex.ru'))},

    'log_enabled' => true,
    'log_file' => dirname(__DIR__) . '/data/cabinet.log',
];
`;

mkdirSync(dirname(outFile), { recursive: true });
writeFileSync(outFile, config, 'utf8');
console.log('Wrote', outFile);
